#pragma once

#if ENABLE(GPU_PROCESS) && ENABLE(WEBGL)

#include "SharedPreferencesForWebProcess.h"
#include "StreamConnectionWorkQueue.h"
#include "StreamMessageReceiver.h"
#include "StreamServerConnection.h"
#include <WebCore/GraphicsContextGL.h>
#include <wtf/HashMap.h>
#include <wtf/TZoneMalloc.h>

namespace WebKit {

// Receives a WebGL context's GL calls, on the stream connection of its RemoteGraphicsContextGLResources, and makes them
// on its GraphicsContextGL. Only used on the WebGL work queue.
// The implementation is largely generated by running Tools/Scripts/generate-gpup-webgl.
class RemoteGraphicsContextGL final : public IPC::StreamMessageReceiver {
    WTF_MAKE_TZONE_ALLOCATED(RemoteGraphicsContextGL);
public:
    static Ref<RemoteGraphicsContextGL> create(IPC::StreamServerConnection&, IPC::StreamConnectionWorkQueue&, WebCore::GraphicsContextGL&, const SharedPreferencesForWebProcess&);
    ~RemoteGraphicsContextGL();

    std::optional<SharedPreferencesForWebProcess> sharedPreferencesForWebProcess() const { return m_sharedPreferencesForWebProcess; }

    // The GL names of the web process's object names, which RemoteGraphicsContextGLResources's messages also take.
    bool isValidObjectName(uint32_t name) const { return m_objectNames.isValidKey(name); }
    uint32_t objectName(uint32_t name) const { return m_objectNames.get(name); }
    uint32_t takeObjectName(uint32_t name) { return m_objectNames.take(name); }
    void addObjectName(uint32_t name, uint32_t object) { m_objectNames.add(name, object); }

private:
    RemoteGraphicsContextGL(IPC::StreamServerConnection&, IPC::StreamConnectionWorkQueue&, WebCore::GraphicsContextGL&, const SharedPreferencesForWebProcess&);

    IPC::StreamConnectionWorkQueue& workQueue() const { return m_workQueue; }

    void didReceiveStreamMessage(IPC::StreamServerConnection&, IPC::Decoder&) final;

    // Messages to be received.
    void ensureExtensionEnabled(WebCore::GCGLExtension);
    void getErrors(CompletionHandler<void(GCGLErrorCodeSet)>&&);
    void drawBuffers(std::span<const uint32_t>);
    void drawBuffersEXT(std::span<const uint32_t>);
    void invalidateFramebuffer(uint32_t target, std::span<const uint32_t> attachments);
    void invalidateSubFramebuffer(uint32_t target, std::span<const uint32_t> attachments, int32_t x, int32_t y, int32_t width, int32_t height);

#include "RemoteGraphicsContextGLFunctionsGenerated.h" // NOLINT

    const Ref<IPC::StreamServerConnection> m_connection;
    const Ref<IPC::StreamConnectionWorkQueue> m_workQueue;
    const Ref<WebCore::GraphicsContextGL> m_context;
    const SharedPreferencesForWebProcess m_sharedPreferencesForWebProcess;
    HashMap<uint32_t, PlatformGLObject, IntHash<uint32_t>, WTF::UnsignedWithZeroKeyHashTraits<uint32_t>> m_objectNames;
};

} // namespace WebKit

#endif

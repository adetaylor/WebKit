import sys
import string

keywordsText = open(sys.argv[1]).read()

# A second argument signifies that the output
# should be redirected to a file
redirect_to_file = len(sys.argv) > 2

# Change stdout to point to the file if requested
if redirect_to_file:
    file_output = open(sys.argv[-1], "w")
    sys.stdout = file_output


# Observed weights of the most common keywords, rounded to 2.s.d
keyWordWeights = {
    "catch": 0.01,
    "try": 0.01,
    "while": 0.01,
    "case": 0.01,
    "break": 0.01,
    "new": 0.01,
    "in": 0.01,
    "typeof": 0.02,
    "true": 0.02,
    "false": 0.02,
    "for": 0.03,
    "null": 0.03,
    "else": 0.03,
    "return": 0.13,
    "var": 0.13,
    "if": 0.16,
    "function": 0.18,
    "this": 0.18,
}


def allWhitespace(str):
    for c in str:
        if not(c in string.whitespace):
            return False
    return True


def parseKeywords(keywordsText):

    if sys.platform == "cygwin":
        keywordsText = keywordsText.replace("\r\n", "\n")

    lines = keywordsText.split("\n")
    lines = [line.split("#")[0] for line in lines]
    lines = [line for line in lines if (not allWhitespace(line))]
    name = lines[0].split()
    terminator = lines[-1]

    if not name[0] == "@begin":
        raise Exception("expected description beginning with @begin")
    if not terminator == "@end":
        raise Exception("expected description ending with @end")

    lines = lines[1:-1]  # trim off the old heading
    return [line.split() for line in lines]


def tokenName(word, value):
    if value == "RESERVED":
        return "reserved"
    if value == "RESERVED_IF_STRICT":
        return "reservedIfStrict"
    return word + "Keyword"


def hexByte(c):
    return "0x%02X" % ord(c)


def printAsSwift(keywords):
    entries = [(word, tokenName(word, value)) for word, value in keywords]
    maxLength = max(len(word) for word, _ in entries)

    print("// This file was generated by KeywordLookupGenerator.py.  Do not edit.")
    print("")
    print("internal import JSCSwiftBoundary")
    print("")
    print("extension Lexer {")
    print("    /// One more than the longest keyword, so that the character after any keyword can be read.")
    print("    static var maxTokenLength: Int { %d }" % (maxLength + 1))
    print("")
    print("    /// The keyword at the cursor and its length, if the character after it cannot continue an identifier.")
    print("    func keywordAtCursor() -> (type: JSC.JSTokenType, name: JSC.JSParseWellKnownName, length: Int)? {")
    print("        // One range check for the whole window; the reads below are at constant offsets into it. The wrapping add keeps")
    print("        // the window's count a constant; a wrapped end is caught by the range's own check.")
    print("        let window = source.extracting(code..<code &+ Self.maxTokenLength)")
    print("        switch window[0] {")
    for first in sorted(set(word[0] for word, _ in entries)):
        # Most frequent first (keyWordWeights); at most one test matches, since each ends at a character that cannot
        # continue an identifier. The sort is stable, so equal weights stay in the table's order.
        group = sorted([e for e in entries if e[0][0] == first], key=lambda e: -keyWordWeights.get(e[0], 0))
        print("        case %s: // %s" % (hexByte(first), first))
        for word, token in group:
            operands = ["window[%d] == %s" % (i, hexByte(c)) for i, c in enumerate(word) if i > 0]
            operands.append("window[%d].cannotBeIdentPartOrEscapeStart" % len(word))
            print("            if " + "\n                && ".join(operands) + "\n            {")
            print("                return (.%s, .%sKeyword, %d)" % (token, word, len(word)))
            print("            }")
        print("            return nil")
    print("        default:")
    print("            return nil")
    print("        }")
    print("    }")
    print("")
    print("    /// The keyword `characters` spell, if any.")
    print("    static func keywordToken<Characters: LexerCharacter>(of characters: Span<Characters>) -> JSC.JSTokenType? {")
    print("        switch characters.count {")
    for length in sorted(set(len(word) for word, _ in entries)):
        print("        case %d:" % length)
        for word, token in entries:
            if len(word) != length:
                continue
            operands = ["characters[%d] == %s" % (i, hexByte(c)) for i, c in enumerate(word)]
            print("            if " + "\n                && ".join(operands) + "\n            {")
            print("                return .%s" % token)
            print("            }")
        print("            return nil")
    print("        default:")
    print("            return nil")
    print("        }")
    print("    }")
    print("}")


printAsSwift(parseKeywords(keywordsText))

# Close the redirected file if requested
if (redirect_to_file):
    file_output.close()
    sys.stdout = sys.__stdout__

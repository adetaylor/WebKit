// The CGPath of a Path of a rounded rect (Path::platformPath() after addRoundedRect()), and of a rect with a rounded hole,
// which GraphicsContextCG::fillRectWithRoundedHole() fills even-odd: the hole goes in as a rect if it has no radii.
private func roundedRectPath(_ roundedRect: CGRendererRoundedRect) -> CGMutablePath {
    let path = CGMutablePath()
    CGRendererRoundedRectSegment(roundedRect).add(to: path)
    return path
}

private func rectWithRoundedHolePath(_ rect: CGRect, _ hole: CGRendererRoundedRect) -> CGMutablePath {
    let path = CGMutablePath()
    CGRendererAddRect(path, rect)
    if hole.hasNonZeroRadii {
        CGRendererRoundedRectSegment(hole).add(to: path)
    } else {
        CGRendererAddRect(path, hole.cgRect)
    }
    return path
}

private func colorDataAreEqual(_ a: CGRendererColorData, _ b: CGRendererColorData) -> Bool {
    a.c1 == b.c1 && a.c2 == b.c2 && a.c3 == b.c3 && a.alpha == b.alpha && a.packedColor == b.packedColor
        && a.colorSpace == b.colorSpace && a.form == b.form && a.isSemantic == b.isSemantic
        && a.usesFunctionSerialization == b.usesFunctionSerialization
}

// The CGColors of the last few packed colors this renderer set. A context is used by one thread at a time.
@usableFromInline @frozen struct CGRendererColorCache {
    @inlinable
    init() {}

    private var keys: (UInt32, UInt32, UInt32, UInt32) = (0, 0, 0, 0)
    private var colors: (CGColor?, CGColor?, CGColor?, CGColor?) = (nil, nil, nil, nil)
    private var next = 0

    mutating func color(_ packed: UInt32) -> CGColor {
        if keys.0 == packed, let color = colors.0 {
            return color
        }
        if keys.1 == packed, let color = colors.1 {
            return color
        }
        if keys.2 == packed, let color = colors.2 {
            return color
        }
        if keys.3 == packed, let color = colors.3 {
            return color
        }
        let color = cgColor(packed: packed)
        switch next {
        case 0:
            keys.0 = packed
            colors.0 = color
        case 1:
            keys.1 = packed
            colors.1 = color
        case 2:
            keys.2 = packed
            colors.2 = color
        default:
            keys.3 = packed
            colors.3 = color
        }
        next = (next + 1) & 3
        return color
    }
}


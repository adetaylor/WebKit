// std::max's choice: the first argument unless it is less than the second, so -0 and NaN stay.
private func cxxMax(_ a: Float, _ b: Float) -> Float {
    a < b ? b : a
}

private func cxxMin(_ a: Float, _ b: Float) -> Float {
    b < a ? b : a
}

private func cxxMax(_ a: CGFloat, _ b: CGFloat) -> CGFloat {
    a < b ? b : a
}

private func cxxMin(_ a: CGFloat, _ b: CGFloat) -> CGFloat {
    b < a ? b : a
}

// WTF's clampTo<int>(float): NaN gives INT_MIN.
private func clampToInt(_ value: Float) -> Int32 {
    if value >= 2_147_483_648 {
        return .max
    }
    if !(value > -2_147_483_648) {
        return .min
    }
    return Int32(value)
}

// C++'s float to int conversion where it's undefined, as the processor does it: arm64 saturates and gives 0 for NaN, x86
// gives INT_MIN.
private func cxxIntConversion(_ value: Float) -> Int32 {
    if value.isNaN || value >= 2_147_483_648 || value < -2_147_483_648 {
        #if arch(arm64)
        return value.isNaN ? 0 : (value < 0 ? .min : .max)
        #else
        return .min
        #endif
    }
    return Int32(value)
}

// truncateDoubleToInt32(), which converts as the processor does too.
private func cxxIntConversion(_ value: Double) -> Int32 {
    if value.isNaN || value >= 2_147_483_648 || value <= -2_147_483_649 {
        #if arch(arm64)
        return value.isNaN ? 0 : (value < 0 ? .min : .max)
        #else
        return .min
        #endif
    }
    return Int32(value)
}

// std::midpoint() of two floats, which halves them separately where their sum could overflow.
private func cxxMidpoint(_ a: Float, _ b: Float) -> Float {
    let low = Float.leastNormalMagnitude * 2
    let high = Float.greatestFiniteMagnitude / 2
    if abs(a) <= high && abs(b) <= high {
        return (a + b) / 2
    }
    if abs(a) < low {
        return a + b / 2
    }
    if abs(b) < low {
        return a / 2 + b
    }
    return a / 2 + b / 2
}

// C++'s double to unsigned conversion where it's undefined, as arm64 does it: saturated, and 0 for NaN.
private func cxxUnsignedConversion(_ value: Double) -> UInt32 {
    if value.isNaN || value <= -1 {
        return 0
    }
    if value >= 4_294_967_296 {
        return .max
    }
    return UInt32(value)
}


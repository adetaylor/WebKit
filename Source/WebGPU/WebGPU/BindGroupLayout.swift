// One per GPUBindGroupLayout, owned by the C++ shell WebGPU::Metal::BindGroupLayout through an opaque box. Owns the
// entries, the per-stage argument encoders and argument indices, the counts and the label, and creates layouts
// (Device::createBindGroupLayout). BindGroupImpl and the encoders read it directly. It also holds the Device.
// Used only on its Instance's API thread, so not Sendable.
@_expose(Cxx)
final class BindGroupLayoutImpl {
    // nil when the stage has no arguments, or for an invalid layout.
    private let vertexEncoder: (any MTLArgumentEncoder)?
    private let fragmentEncoder: (any MTLArgumentEncoder)?
    private let computeEncoder: (any MTLArgumentEncoder)?
    private var label: WTF.String
    private let backingIsValid: Bool

    /// Ascending binding, unique.
    ///
    /// The array-length entries of generated layouts are not kept.
    let entries: [LayoutEntry]
    /// The indices of each stage's encoder arguments: ascending, unique.
    let argumentIndices: PerStage<[UInt32]>
    /// argumentIndices as a bit mask, for a stage whose indices are all below 64; nil otherwise.
    let argumentIndexBits: PerStage<UInt64?>
    /// Each encoder's encodedLength, which never changes; 0 without an encoder.
    private let encodedLengths: PerStage<UInt>
    let counts: LayoutCounts
    /// Exact under the pair invariant: a PipelineLayoutImpl dies with its shell.
    weak var autogeneratedPipelineLayout: PipelineLayoutImpl?
    // Declared last, so that the device outlives the rest of the layout. deviceImpl is for the compatibility cache and
    // for device identity.
    let deviceImpl: DeviceImpl
    let device: WebGPU.Metal.Device
    @_expose(Cxx)
    func shellDevice() -> WebGPU.Metal.Device { device }

    init(
        encoders: PerStage<(any MTLArgumentEncoder)?>,
        entries: [LayoutEntry],
        argumentIndices: PerStage<[UInt32]>,
        counts: LayoutCounts,
        label: WTF.String,
        device: WebGPU.Metal.Device,
        deviceImpl: DeviceImpl
    ) {
        vertexEncoder = encoders.vertex
        fragmentEncoder = encoders.fragment
        computeEncoder = encoders.compute
        self.label = label
        backingIsValid = true
        self.entries = entries
        self.argumentIndices = argumentIndices
        argumentIndexBits = PerStage(
            vertex: indexBits(argumentIndices.vertex),
            fragment: indexBits(argumentIndices.fragment),
            compute: indexBits(argumentIndices.compute)
        )
        encodedLengths = PerStage(
            vertex: UInt(encoders.vertex?.encodedLength ?? 0),
            fragment: UInt(encoders.fragment?.encodedLength ?? 0),
            compute: UInt(encoders.compute?.encodedLength ?? 0)
        )
        self.counts = counts
        self.deviceImpl = deviceImpl
        self.device = device
        applyLabelToEncoders()
    }

    private init(invalidFor device: WebGPU.Metal.Device, _ deviceImpl: DeviceImpl) {
        vertexEncoder = nil
        fragmentEncoder = nil
        computeEncoder = nil
        label = WTF.String()
        backingIsValid = false
        entries = []
        argumentIndices = PerStage(repeating: [])
        argumentIndexBits = PerStage(repeating: 0)
        encodedLengths = PerStage(repeating: 0)
        counts = LayoutCounts()
        self.deviceImpl = deviceImpl
        self.device = device
    }

    static func invalid(_ device: WebGPU.Metal.Device, _ deviceImpl: DeviceImpl) -> BindGroupLayoutImpl {
        BindGroupLayoutImpl(invalidFor: device, deviceImpl)
    }

    private func entryIndex(binding: UInt32) -> Int? {
        var low = 0
        var high = entries.count
        while low < high {
            let middle = low + (high - low) / 2
            let candidate = entries[middle].binding
            if candidate == binding {
                return middle
            }
            if candidate < binding {
                low = middle + 1
            } else {
                high = middle
            }
        }
        return nil
    }

    func entry(binding: UInt32) -> LayoutEntry? {
        entryIndex(binding: binding).map { entries[$0] }
    }

    /// Uses the device's compatibility cache.
    func errorValidatingCompatibility(with other: BindGroupLayoutImpl) -> String? {
        // A layout always matches itself (every comparison below is reflexive), and the cache entry the full check
        // would add for it is only ever looked up for this same layout.
        if self === other {
            return nil
        }
        if deviceImpl.isCachedCompatible(counts.identifier, other.counts.identifier) {
            return nil
        }

        if counts.isAutoGenerated != other.counts.isAutoGenerated || autogeneratedPipelineLayout !== other.autogeneratedPipelineLayout {
            return "Auto-generated layouts mismatch"
        }

        if entries.count != other.entries.count {
            return "entries.size()(\(entries.count)) > otherEntries.size()(\(other.entries.count))"
        }

        for (entry, otherEntry) in zip(entries, other.entries)
        where entry.binding != otherEntry.binding || entry.visibility != otherEntry.visibility
            || !entry.layout.layoutEquals(otherEntry.layout)
        {
            return "entries are not equal"
        }

        deviceImpl.setCachedCompatible(counts.identifier, other.counts.identifier)
        return nil
    }

    @_expose(Cxx)
    func isValid() -> Bool {
        backingIsValid
    }

    @_expose(Cxx)
    func setLabel(_ newLabel: WTF.String) {
        label = newLabel
        applyLabelToEncoders()
    }

    private func applyLabelToEncoders() {
        let nsLabel = CxxBridging.convertWTFStringToNSString(label)
        vertexEncoder?.label = nsLabel as String?
        fragmentEncoder?.label = nsLabel as String?
        computeEncoder?.label = nsLabel as String?
    }

    /// `stage` is a Stage raw value; any other value has no encoder.
    func encodedLength(_ stage: UInt8) -> UInt {
        switch stage {
        case 0: return encodedLengths.vertex
        case 1: return encodedLengths.fragment
        case 2: return encodedLengths.compute
        default: return 0
        }
    }

    func vertexArgumentEncoder() -> (any MTLArgumentEncoder)? {
        vertexEncoder
    }

    func fragmentArgumentEncoder() -> (any MTLArgumentEncoder)? {
        fragmentEncoder
    }

    func computeArgumentEncoder() -> (any MTLArgumentEncoder)? {
        computeEncoder
    }

    @_expose(!Cxx)
    func uniqueId() -> UInt32 {
        counts.identifier
    }

    // Called from ~BindGroupLayout.
    @_expose(Cxx)
    func removeFromDeviceCache() {
        deviceImpl.removeCachedBindGroupLayout(uniqueId())
    }
}

// MARK: - Creation

/// Reports its validation errors, and returns an invalid Impl on failure.
@_expose(Cxx)
func createBindGroupLayoutImpl(
    _ device: WebGPU.Metal.Device,
    _ deviceImpl: DeviceImpl,
    _ descriptor: borrowing WebGPU.BindGroupLayoutDescriptor
) -> BindGroupLayoutImpl {
    guard deviceImpl.isValid() else {
        return .invalid(device, deviceImpl)
    }

    let descriptorEntries: Span<WebGPU.BindGroupLayoutEntry> = descriptor.entriesSpan()
    var entries: [ResolvedLayoutEntry] = []
    entries.reserveCapacity(descriptorEntries.count)
    for index in descriptorEntries.indices {
        let entry = descriptorEntries[index]
        guard let layout = layoutBinding(entry) else {
            deviceImpl.generateAValidationError(
                "Entry for binding \(entry.binding) does not have exactly one of buffer, sampler, texture, storageTexture and externalTexture"
            )
            return .invalid(device, deviceImpl)
        }
        entries.append(
            ResolvedLayoutEntry(
                binding: entry.binding,
                metalBinding: PerStage(repeating: entry.binding),
                visibility: StageMask(rawValue: entry.visibility.toRaw()),
                layout: layout
            )
        )
    }

    return makeBindGroupLayoutImpl(
        device: device,
        deviceImpl: deviceImpl,
        label: descriptor.label,
        entries: entries,
        isAutoGenerated: false
    )
}

@_expose(Cxx)
func makeInvalidBindGroupLayoutImpl(_ device: WebGPU.Metal.Device, _ deviceImpl: DeviceImpl) -> BindGroupLayoutImpl {
    .invalid(device, deviceImpl)
}

/// The binding layout of an entry, which has to have exactly one of the binding layout members.
private func layoutBinding(_ entry: WebGPU.BindGroupLayoutEntry) -> LayoutBinding? {
    // FIXME: The specification makes an entry with an external texture and another binding layout
    // a validation error. An external texture binding layout has always taken precedence over the
    // other ones instead, and fast/webgpu/nocrash/fuzz-274317.html relies on it.
    if Optional(fromCxx: entry.externalTexture) != nil {
        return .externalTexture
    }

    let buffer = Optional(fromCxx: entry.buffer)
    let sampler = Optional(fromCxx: entry.sampler)
    let texture = Optional(fromCxx: entry.texture)
    let storageTexture = Optional(fromCxx: entry.storageTexture)
    var memberCount = 0
    memberCount += buffer != nil ? 1 : 0
    memberCount += sampler != nil ? 1 : 0
    memberCount += texture != nil ? 1 : 0
    memberCount += storageTexture != nil ? 1 : 0
    guard memberCount == 1 else {
        return nil
    }

    if let buffer {
        let type: LayoutBufferType =
            switch buffer.type {
            case .Uniform: .uniform
            case .Storage: .storage
            case .ReadOnlyStorage: .readOnlyStorage
            @unknown default: preconditionFailure("unknown WebGPU::BufferBindingType")
            }
        return .buffer(
            BufferLayout(
                type: type,
                hasDynamicOffset: buffer.hasDynamicOffset,
                minBindingSize: buffer.minBindingSize,
                bufferSizeForBinding: 0
            )
        )
    }
    if let sampler {
        return .sampler(SamplerLayout(type: sampler.type))
    }
    if let texture {
        return .texture(
            TextureLayout(sampleType: texture.sampleType, viewDimension: texture.viewDimension, multisampled: texture.multisampled)
        )
    }
    if let storageTexture {
        return .storageTexture(
            StorageTextureLayout(access: storageTexture.access, format: storageTexture.format, viewDimension: storageTexture.viewDimension)
        )
    }
    return nil
}

/// What one argument of a stage's argument encoder is, before its index is known.
private struct ArgumentKind {
    let dataType: MTLDataType
    let access: MTLBindingAccess
}

private struct Argument {
    let index: UInt32
    let kind: ArgumentKind
}

private let sampledTextureArgument = ArgumentKind(dataType: .texture, access: .readOnly)
private let bufferSizeArgument = ArgumentKind(dataType: .int, access: .readOnly)

/// The two planes, then the uvRemapping, colorSpaceConversion and primariesConversion matrices, then the visible size.
private let externalTextureArguments = [
    sampledTextureArgument,
    sampledTextureArgument,
    ArgumentKind(dataType: .float3x2, access: .readOnly),
    ArgumentKind(dataType: .float4x3, access: .readOnly),
    ArgumentKind(dataType: .float3x3, access: .readOnly),
    ArgumentKind(dataType: .uint2, access: .readOnly),
]

private func bufferArgument(_ type: LayoutBufferType, visibility: StageMask) -> ArgumentKind? {
    switch type {
    case .uniform, .readOnlyStorage:
        return ArgumentKind(dataType: .pointer, access: .readOnly)
    case .storage:
        if visibility.contains(.vertex) {
            return nil
        }
        return ArgumentKind(dataType: .pointer, access: .readWrite)
    case .arrayLength:
        return ArgumentKind(dataType: .pointer, access: .readOnly)
    case .float3x2:
        return ArgumentKind(dataType: .float3x2, access: .readOnly)
    case .float4x3:
        return ArgumentKind(dataType: .float4x3, access: .readOnly)
    case .float3x3:
        return ArgumentKind(dataType: .float3x3, access: .readOnly)
    case .uint2:
        return ArgumentKind(dataType: .uint2, access: .readOnly)
    }
}

private func textureArgument(_ texture: TextureLayout) -> ArgumentKind? {
    if texture.multisampled
        && (texture.viewDimension != WebGPU.TextureViewDimension._2d || texture.sampleType == WebGPU.TextureSampleType.Float)
    {
        return nil
    }
    return sampledTextureArgument
}

private func storageTextureArgument(
    _ storageTexture: StorageTextureLayout,
    device: WebGPU.Metal.Device,
    visibility: StageMask
) -> ArgumentKind? {
    if visibility.contains(.vertex) && storageTexture.access != WebGPU.StorageTextureAccess.ReadOnly {
        return nil
    }
    if storageTexture.viewDimension == WebGPU.TextureViewDimension.Cube
        || storageTexture.viewDimension == WebGPU.TextureViewDimension.CubeArray
    {
        return nil
    }
    if !hasStorageBindingCapability(storageTexture.format, device, storageTexture.access) {
        return nil
    }
    return ArgumentKind(dataType: .texture, access: .readWrite)
}

private func makeArgumentDescriptor(_ argument: Argument) -> MTLArgumentDescriptor {
    let descriptor = MTLArgumentDescriptor()
    descriptor.dataType = argument.kind.dataType
    descriptor.access = argument.kind.access
    descriptor.index = Int(argument.index)
    return descriptor
}

extension Stage {
    func layoutStorageBufferLimit(_ limits: WebGPU.Limits) -> UInt32 {
        switch self {
        case .vertex: limits.maxStorageBuffersInVertexStage
        case .fragment: limits.maxStorageBuffersInFragmentStage
        case .compute: limits.maxStorageBuffersPerShaderStage
        }
    }

    func layoutStorageTextureLimit(_ limits: WebGPU.Limits) -> UInt32 {
        switch self {
        case .vertex: limits.maxStorageTexturesInVertexStage
        case .fragment: limits.maxStorageTexturesInFragmentStage
        case .compute: limits.maxStorageTexturesPerShaderStage
        }
    }
}

/// The bit mask of `indices`, or nil when one is 64 or more.
private func indexBits(_ indices: [UInt32]) -> UInt64? {
    var bits: UInt64 = 0
    for index in indices {
        guard index < 64 else {
            return nil
        }
        bits |= UInt64(1) << index
    }
    return bits
}

extension PerStage {
    /// In place, so that an array or dictionary element is not copied on write.
    fileprivate mutating func mutateLayoutStage<R>(_ stage: Stage, _ body: (inout T) -> R) -> R {
        switch stage {
        case .vertex: body(&vertex)
        case .fragment: body(&fragment)
        case .compute: body(&compute)
        }
    }
}

/// Creates a bind group layout from resolved entries.
///
/// The entries of generated layouts have their own Metal binding per stage and include array-length entries; their
/// errors are not reported.
func makeBindGroupLayoutImpl(
    device: WebGPU.Metal.Device,
    deviceImpl: DeviceImpl,
    label: WTF.String,
    entries descriptorEntries: [ResolvedLayoutEntry],
    isAutoGenerated: Bool
) -> BindGroupLayoutImpl {
    guard deviceImpl.isValid() else {
        return .invalid(device, deviceImpl)
    }

    func reportError(_ message: String) {
        if !isAutoGenerated {
            deviceImpl.generateAValidationError(message)
        }
    }

    var descriptorEntries = descriptorEntries
    if !isAutoGenerated {
        descriptorEntries.sort { $0.binding < $1.binding }
    }

    let limits = deviceImpl.capabilities.limits
    let maxBindingIndex = limits.maxBindingsPerBindGroup
    var arguments = PerStage<[Argument]>(repeating: [])
    var counts = LayoutCounts()
    var maxIndices = PerStage<UInt32>(repeating: 0)
    // Only its truncation to 32 bits is stored.
    var sizeOfDynamicOffsets = PerStage<UInt64>(repeating: 0)
    var bindingOffset = PerStage<UInt32>(repeating: 0)
    var bufferCounts = PerStage<UInt32>(repeating: 0)
    // The array-length entries of a generated layout, by the binding of the buffer they measure. Lookups only.
    var slotForEntry = PerStage<[UInt32: (metalBinding: PerStage<UInt32>, visibility: StageMask)]>(repeating: [:])
    var usedBindingSlots = Set<UInt32>()
    var entries: [LayoutEntry] = []
    entries.reserveCapacity(descriptorEntries.count)

    for entry in descriptorEntries {
        let bufferLayout = entry.layout.bufferLayout
        if !entry.layout.isArrayLength {
            let isDuplicated = usedBindingSlots.contains(entry.binding)
            if entry.binding >= maxBindingIndex || isDuplicated {
                reportError(
                    "Binding index is invalid: entry.binding(\(entry.binding)) >= maxBindingIndex(\(maxBindingIndex)) || entry binding \(isDuplicated ? "is" : "is not") duplicated"
                )
                return .invalid(device, deviceImpl)
            }
            usedBindingSlots.insert(entry.binding)
        }

        if let bufferLayout, bufferLayout.hasDynamicOffset {
            if bufferLayout.type == .uniform {
                counts.dynamicUniformBuffers &+= 1
                if counts.dynamicUniformBuffers > limits.maxDynamicUniformBuffersPerPipelineLayout {
                    reportError(
                        "Too many dynamic uniform buffers: used(\(counts.dynamicUniformBuffers)), limit(\(limits.maxDynamicUniformBuffersPerPipelineLayout))"
                    )
                    return .invalid(device, deviceImpl)
                }
            }
            if bufferLayout.type == .storage || bufferLayout.type == .readOnlyStorage {
                counts.dynamicStorageBuffers &+= 1
                if counts.dynamicStorageBuffers > limits.maxDynamicStorageBuffersPerPipelineLayout {
                    reportError(
                        "Too many dynamic storage buffers: used(\(counts.dynamicStorageBuffers)), limit(\(limits.maxDynamicStorageBuffersPerPipelineLayout))"
                    )
                    return .invalid(device, deviceImpl)
                }
            }
        }

        if let bufferLayout, bufferLayout.type == .arrayLength {
            let measuredBinding = UInt32(truncatingIfNeeded: bufferLayout.bufferSizeForBinding)
            for stage in Stage.allCases where entry.visibility.contains(stage.bit) {
                slotForEntry.mutateLayoutStage(stage) {
                    $0[measuredBinding] = (metalBinding: entry.metalBinding, visibility: entry.visibility)
                }
            }
            continue
        }

        let primaryArgument: ArgumentKind?
        var layoutError: String?
        var isExternalTexture = false
        switch entry.layout {
        case .buffer(let buffer):
            primaryArgument = bufferArgument(buffer.type, visibility: entry.visibility)
            layoutError = "Buffer layout is not valid"
        case .sampler:
            primaryArgument = ArgumentKind(dataType: .sampler, access: .readOnly)
            layoutError = "Sampler layout is not valid"
        case .texture(let texture):
            primaryArgument = textureArgument(texture)
            layoutError = "Texture layout not valid"
        case .storageTexture(let storageTexture):
            primaryArgument = storageTextureArgument(storageTexture, device: device, visibility: entry.visibility)
            layoutError = "Storage texture layout not valid"
        case .externalTexture:
            isExternalTexture = true
            primaryArgument = externalTextureArguments[0]
        }

        guard let primaryArgument else {
            if let layoutError {
                reportError(layoutError)
            }
            return .invalid(device, deviceImpl)
        }
        let argumentCount = isExternalTexture ? externalTextureArguments.count : 1

        var argumentBufferIndices = PerStage<UInt32?>(repeating: nil)
        var bufferSizeArgumentBufferIndices = PerStage<UInt32?>(repeating: nil)
        var dynamicOffsets = PerStage<UInt32?>(repeating: nil)
        for stage in Stage.allCases where entry.visibility.contains(stage.bit) {
            let argumentBufferIndex = isAutoGenerated ? entry.metalBinding[stage] : entry.binding &+ bindingOffset[stage]
            argumentBufferIndices[stage] = argumentBufferIndex
            if entry.layout.hasDynamicOffset {
                dynamicOffsets[stage] = UInt32(truncatingIfNeeded: sizeOfDynamicOffsets[stage])
                sizeOfDynamicOffsets[stage] &+= UInt64(MemoryLayout<UInt32>.size)
            }
            if let bufferLayout {
                bufferCounts[stage] &+= 1
                bufferSizeArgumentBufferIndices[stage] = bufferCounts[stage]
                if bufferLayout.type == .uniform {
                    counts.uniformBuffers[stage] &+= 1
                    if counts.uniformBuffers[stage] > limits.maxUniformBuffersPerShaderStage {
                        reportError(
                            "Uniform buffers count(\(counts.uniformBuffers[stage])) exceeded max count per stage(\(limits.maxUniformBuffersPerShaderStage))"
                        )
                        return .invalid(device, deviceImpl)
                    }
                }
                if bufferLayout.type == .storage || bufferLayout.type == .readOnlyStorage {
                    let maxStorageBuffers = stage.layoutStorageBufferLimit(limits)
                    counts.storageBuffers[stage] &+= 1
                    if counts.storageBuffers[stage] > maxStorageBuffers {
                        reportError(
                            "Storage buffers count(\(counts.storageBuffers[stage])) exceeded max count per stage(\(maxStorageBuffers))"
                        )
                        return .invalid(device, deviceImpl)
                    }
                }
            }
            if case .sampler = entry.layout {
                counts.samplers[stage] &+= 1
                if counts.samplers[stage] > limits.maxSamplersPerShaderStage {
                    reportError(
                        "Sampler count(\(counts.samplers[stage])) exceeded max count per stage(\(limits.maxSamplersPerShaderStage))"
                    )
                    return .invalid(device, deviceImpl)
                }
            }
            if case .storageTexture = entry.layout {
                let maxStorageTextures = stage.layoutStorageTextureLimit(limits)
                counts.storageTextures[stage] &+= 1
                if counts.storageTextures[stage] > maxStorageTextures {
                    reportError(
                        "Storage texture count(\(counts.storageTextures[stage])) exceeded max count per stage(\(maxStorageTextures))"
                    )
                    return .invalid(device, deviceImpl)
                }
            }
            if case .texture = entry.layout {
                counts.textures[stage] &+= 1
                if counts.textures[stage] > limits.maxSampledTexturesPerShaderStage {
                    reportError(
                        "Texture count(\(counts.textures[stage])) exceeded max count per stage(\(limits.maxSampledTexturesPerShaderStage))"
                    )
                    return .invalid(device, deviceImpl)
                }
            }

            for argumentIndex in 0..<argumentCount {
                let index = argumentBufferIndex &+ UInt32(argumentIndex)
                maxIndices[stage] = max(maxIndices[stage], index)
                let kind = isExternalTexture ? externalTextureArguments[argumentIndex] : primaryArgument
                arguments.mutateLayoutStage(stage) { $0.append(Argument(index: index, kind: kind)) }
            }

            if isExternalTexture {
                bindingOffset[stage] &+= UInt32(externalTextureArguments.count - 1)
            }
        }

        entries.append(
            LayoutEntry(
                binding: entry.binding,
                visibility: entry.visibility,
                layout: entry.layout,
                argumentBufferIndices: argumentBufferIndices,
                bufferSizeArgumentBufferIndices: bufferSizeArgumentBufferIndices,
                dynamicOffsets: dynamicOffsets,
                dynamicOffsetsIndex: LayoutEntry.noDynamicOffsetsIndex,
                access: primaryArgument.access
            )
        )
    }

    // `entries` is still in descriptor order, which is binding order: only explicit layouts have dynamic offsets.
    if sizeOfDynamicOffsets.vertex != 0 || sizeOfDynamicOffsets.fragment != 0 || sizeOfDynamicOffsets.compute != 0 {
        precondition(!isAutoGenerated)
        var nextDynamicOffsetIndex: UInt32 = 0
        for index in entries.indices where entries[index].layout.hasDynamicOffset {
            entries[index].dynamicOffsetsIndex = nextDynamicOffsetIndex
            nextDynamicOffsetIndex &+= 1
        }
    }

    var encoders = PerStage<(any MTLArgumentEncoder)?>(repeating: nil)
    var argumentIndices = PerStage<[UInt32]>(repeating: [])
    for stage in Stage.allCases {
        if bufferCounts[stage] != 0 {
            let maxIndex = maxIndices[stage]
            for index in entries.indices {
                guard let bufferSizeIndex = entries[index].bufferSizeArgumentBufferIndices[stage] else {
                    continue
                }
                let resolvedIndex: UInt32
                if !isAutoGenerated {
                    resolvedIndex = bufferSizeIndex &+ maxIndex
                } else if let slot = slotForEntry[stage][entries[index].binding], slot.visibility.contains(stage.bit) {
                    resolvedIndex = slot.metalBinding[stage]
                } else {
                    entries[index].bufferSizeArgumentBufferIndices[stage] = nil
                    continue
                }
                entries[index].bufferSizeArgumentBufferIndices[stage] = resolvedIndex
                arguments.mutateLayoutStage(stage) { $0.append(Argument(index: resolvedIndex, kind: bufferSizeArgument)) }
            }
        }

        let stageArguments = arguments.mutateLayoutStage(stage) { pending in
            pending.sort { $0.index < $1.index }
            return pending
        }
        if !stageArguments.isEmpty {
            guard let encoder = deviceImpl.device()?.makeArgumentEncoder(arguments: stageArguments.map(makeArgumentDescriptor)) else {
                return .invalid(device, deviceImpl)
            }
            encoders[stage] = encoder
        }

        var indices: [UInt32] = []
        indices.reserveCapacity(stageArguments.count)
        for argument in stageArguments where indices.last != argument.index {
            indices.append(argument.index)
        }
        argumentIndices[stage] = indices
    }

    if deviceImpl.bindGroupLayoutIdsExhausted() {
        deviceImpl.loseTheDevice(WebGPU.DeviceLostReason.Unknown)
        return .invalid(device, deviceImpl)
    }

    counts.sizeOfDynamicOffsets = PerStage(
        vertex: UInt32(truncatingIfNeeded: sizeOfDynamicOffsets.vertex),
        fragment: UInt32(truncatingIfNeeded: sizeOfDynamicOffsets.fragment),
        compute: UInt32(truncatingIfNeeded: sizeOfDynamicOffsets.compute)
    )
    counts.identifier = deviceImpl.takeBindGroupLayoutId()
    counts.isAutoGenerated = isAutoGenerated

    // A generated layout keeps its entries in the order the shader reflection produced them.
    if isAutoGenerated {
        entries.sort { $0.binding < $1.binding }
    }

    return BindGroupLayoutImpl(
        encoders: encoders,
        entries: entries,
        argumentIndices: argumentIndices,
        counts: counts,
        label: label,
        device: device,
        deviceImpl: deviceImpl
    )
}

/// Wraps an Impl made in Swift in a new shell, through DeviceImpl.stagedBindGroupLayoutImpl.
func makeBindGroupLayoutShell(
    _ impl: BindGroupLayoutImpl,
    device: WebGPU.Metal.Device,
    deviceImpl: DeviceImpl
) -> WebGPU.Metal.BindGroupLayout {
    precondition(deviceImpl.stagedBindGroupLayoutImpl == nil)
    deviceImpl.stagedBindGroupLayoutImpl = impl
    return WebGPU.Metal.BindGroupLayout.createWithStagedImpl(device).ptr()
}

namespace WebGPU::Metal {

static_assert(sizeof(WebGPU::PipelineLayoutImpl) == sizeof(void*) && alignof(WebGPU::PipelineLayoutImpl) == alignof(void*));

WTF_MAKE_TZONE_ALLOCATED_IMPL(PipelineLayout);

RefPtr<WebGPU::PipelineLayout> Device::createPipelineLayout(const WebGPU::PipelineLayoutDescriptor& descriptor)
{
    // A descriptor without bind group layouts asks for the layout that pipelines generate. An empty
    // list does too, as it always has through the C API, where it is a null pointer.
    return createPipelineLayout(descriptor, !descriptor.bindGroupLayouts || descriptor.bindGroupLayouts->empty());
}

Ref<PipelineLayout> Device::createPipelineLayout(const WebGPU::PipelineLayoutDescriptor& descriptor, bool isAutogenerated)
{
    auto descriptorBindGroupLayouts = descriptor.bindGroupLayouts.value_or(std::span<const Ref<WebGPU::BindGroupLayout>> { });
    auto& deviceImpl = swiftImpl();
    if (descriptorBindGroupLayouts.empty()) {
        return PipelineLayout::create([&] {
            return makePipelineLayoutImplWithoutBindGroupLayouts(this, deviceImpl, isAutogenerated);
        });
    }
    if (descriptorBindGroupLayouts.size() == 1) {
        auto& bindGroupLayout = metal(descriptorBindGroupLayouts[0].get());
        return PipelineLayout::create([&] {
            return makePipelineLayoutImplWithOneBindGroupLayout(this, deviceImpl, &bindGroupLayout, bindGroupLayout.swiftImpl(), isAutogenerated);
        });
    }
    for (auto& descriptorBindGroupLayout : descriptorBindGroupLayouts) {
        auto& bindGroupLayout = metal(descriptorBindGroupLayout.get());
        appendPipelineLayoutBindGroupLayout(deviceImpl, &bindGroupLayout, bindGroupLayout.swiftImpl());
    }
    return PipelineLayout::create([&] {
        return finishPipelineLayout(this, deviceImpl, isAutogenerated);
    });
}

#pragma mark Shell

template<typename MakeImpl>
Ref<PipelineLayout> PipelineLayout::create(MakeImpl&& makeImpl)
{
    return adoptRef(*new PipelineLayout(std::forward<MakeImpl>(makeImpl)));
}

Ref<PipelineLayout> PipelineLayout::createInvalid(Device& device)
{
    return create([&] {
        return makeInvalidPipelineLayoutImpl(&device);
    });
}

Ref<PipelineLayout> PipelineLayout::createWithStagedImpl(Device& device)
{
    return create([&] {
        return device.swiftImpl().takeStagedPipelineLayoutImpl();
    });
}

template<typename MakeImpl>
PipelineLayout::PipelineLayout(MakeImpl&& makeImpl)
{
    // Initialized from the prvalue directly: no copy, so no extra retain and release.
    new (m_impl) WebGPU::PipelineLayoutImpl(makeImpl());
}

PipelineLayout::~PipelineLayout()
{
    std::destroy_at(&swiftImpl());
}

void PipelineLayout::setLabel(String&&)
{
    // There is no Metal object that represents a pipeline layout.
}

bool PipelineLayout::isValid() const
{
    return swiftImpl().isValid();
}

WebGPU::PipelineLayoutImpl& PipelineLayout::swiftImpl() const
{
    return *std::launder(reinterpret_cast<WebGPU::PipelineLayoutImpl*>(const_cast<std::byte*>(m_impl)));
}

void PipelineLayout::makeInvalid()
{
    swiftImpl().makeInvalid();
}

} // namespace WebGPU::Metal

